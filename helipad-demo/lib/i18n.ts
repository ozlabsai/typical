/** Look an id up in one of the dictionary's maps; an id the dictionary lacks reads as its words. */
export function tr(map: Record<string, string>, id: string): string {
  return map[id] ?? id.replace(/[_-]/g, " ");
}

/** Wrap a numeric run so it stays left-to-right inside Hebrew text (Unicode LRI ... PDI). */
export function ltr(s: string | number): string {
  return `⁦${s}⁩`;
}
