const DICTS: Record<Lang, Record<Key, string>> = { en, he }
export type T = (key: Key, vars?: Record<string, string | number>) => string

/** The one place a UI language maps to a locale (dates, numbers, language names). */
export const locale = (l: Lang) => (l === "he" ? "he-IL" : "en")

interface I18n {
  lang: Lang
  setLang: (l: Lang) => void
  t: T
  /** "Oct 13, 2026"; "—" when unknown */
  date: (iso?: string | null) => string
  /** "Spanish" / "ספרדית" for a language code */
  language: (code: string) => string
}
const Ctx = createContext<I18n>(null!)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem("typically.lang") as Lang) || "en")
  const dir = lang === "he" ? "rtl" : "ltr"
  useEffect(() => {
    localStorage.setItem("typically.lang", lang)
    document.documentElement.lang = lang
    document.documentElement.dir = dir
  }, [lang, dir])
  const value = useMemo<I18n>(() => {
    const dates = new Intl.DateTimeFormat(locale(lang), { dateStyle: "medium" })
    const names = new Intl.DisplayNames([locale(lang)], { type: "language" })
    return {
      lang, setLang,
      t: (key, vars) => (DICTS[lang][key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(vars?.[k] ?? `{${k}}`)),
      date: (iso) => (iso ? dates.format(new Date(iso)) : "—"),
      language: (code) => names.of(code) ?? code,
    }
  }, [lang])
  return (
    <Ctx.Provider value={value}>
      <Direction.Provider dir={dir}>{children}</Direction.Provider>
    </Ctx.Provider>
  )
}

export const useI18n = () => useContext(Ctx)
